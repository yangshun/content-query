import type { ComponentType } from "react";
import type { MDXProps } from "mdx/types.js";
import type { ContentHeading } from "content-query";

/** Hydration timing supported by the standalone React island renderer. */
export type HydrationStrategy = "load" | "visible" | "idle" | "only";
/** A compiled module, usable directly in an application-owned React tree. */
export type MdxModule = {
  default: ComponentType<MDXProps>;
  headings: ContentHeading[];
  [name: string]: unknown;
};
/** A selected browser entry; manifests containing the complete corpus stay on the server. */
export type MdxClientReference = { url: string; css: string[] };
/** Versioned asset output generated by the Vite integration. */
export type MdxAssetManifest = {
  version: 1;
  documents: Record<string, { client?: MdxClientReference; css: string[] }>;
  islands: Record<string, MdxClientReference>;
  assets: string[];
};
/** Asset resolution shared by production manifests and development integration. */
export type MdxAssets = {
  document(collection: string, id: string): MdxClientReference;
  island(id: string): MdxClientReference;
  styles(collection: string, id: string): string[];
};

/** Encodes collection and entry identities without delimiter or prototype collisions. */
export function documentKey(collection: string, id: string): string {
  return JSON.stringify([collection, id]);
}
